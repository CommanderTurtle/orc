const number = value => String(Math.round(value * 1e6) / 1e6);
const quote = value => JSON.stringify(value);
export function normalizeStudio(value, files, assets = {}) {
  if (value === undefined) return undefined;
  if (!value || value.version !== 1 || typeof value.baseEntry !== 'string' || !(value.baseEntry in files)
    || typeof value.generated !== 'string' || !(value.generated in files) || value.generated === value.baseEntry)
    throw Error('Invalid studio source mapping.');
  const tracks = Object.create(null);
  if (!value.tracks || typeof value.tracks !== 'object' || Array.isArray(value.tracks)) throw Error('Invalid studio track map.');
  if (Object.keys(value.tracks || {}).length > 64) throw Error('Studio exceeds 64 track edits.');
  for (const [id, patch] of Object.entries(value.tracks || {})) {
    if (!id || id.length > 1024 || ['__proto__', 'constructor', 'prototype'].includes(id) || !patch || typeof patch !== 'object' || Array.isArray(patch)) throw Error('Invalid studio track.');
    const out = {};
    if (patch.gain !== undefined) { if (!Number.isFinite(patch.gain) || patch.gain < -120 || patch.gain > 12) throw Error('Track gain must be −120…12 dB.'); out.gain = patch.gain; }
    if (patch.preset !== undefined) { if (typeof patch.preset !== 'string' || patch.preset.length > 100) throw Error('Invalid native preset.'); out.preset = patch.preset; }
    if (patch.sample !== undefined) { if (typeof patch.sample !== 'string' || (patch.sample && (!/\.(wav|flac)$/i.test(patch.sample) || !(patch.sample in assets)))) throw Error('Choose an imported WAV/FLAC sample.'); out.sample = patch.sample; }
    if (patch.notes !== undefined) {
      if (!Array.isArray(patch.notes) || patch.notes.length > 1024) throw Error('A piano-roll track supports up to 1024 notes.');
      out.notes = patch.notes.map(n => {
        if (![n.beat, n.length, n.pitch, n.velocity].every(Number.isFinite) || n.beat < 0 || n.beat > 100000
          || n.length <= 0 || n.length > 100000 || !Number.isInteger(n.pitch) || n.pitch < 0 || n.pitch > 127 || n.velocity < 0 || n.velocity > 1)
          throw Error('Invalid piano-roll note.');
        return { beat: n.beat, length: n.length, pitch: n.pitch, velocity: n.velocity };
      });
    }
    if (patch.added) out.added = true;
    if (patch.removed) out.removed = true;
    tracks[id] = out;
  }
  if (value.tempo !== undefined && (!Number.isFinite(value.tempo) || value.tempo < 20 || value.tempo > 400)) throw Error('Tempo must be 20…400 BPM.');
  return { version: 1, baseEntry: value.baseEntry, generated: value.generated, tracks, ...(value.tempo === undefined ? {} : { tempo: value.tempo }) };
}
function pattern(notes) { return `stack([${notes.map(n => `note(${n.pitch}, ${number(n.length)}b, at = ${number(n.beat)}b, velocity = ${number(n.velocity)}).gate(1)`).join(',\n    ')}])`; }
export function studioSource(state, title) {
  const ids = Object.keys(state.tracks), patches = [];
  for (const id of ids) {
    const patch = state.tracks[id]; if (patch.added || patch.removed) continue;
    const fields = [];
    if (patch.gain !== undefined) fields.push(`gain: ${number(patch.gain)}`);
    if (patch.sample) fields.push(`instrument: sample(${quote(patch.sample)})`);
    else if (patch.preset) fields.push(`instrument: synth(${quote(patch.preset)})`);
    if (patch.notes) fields.push(`pattern: ${pattern(patch.notes)}`);
    if (fields.length) patches.push([id, `merge(t, {${fields.join(', ')}})`]);
  }
  const removed = ids.filter(id => state.tracks[id].removed);
  const filter = removed.length ? `filter(original.tracks, fn(t) => ${removed.map(id => `t.id != ${quote(id)}`).join(' && ')})` : 'original.tracks';
  const added = ids.filter(id => state.tracks[id].added && !state.tracks[id].removed).map(id => {
    const p = state.tracks[id], instrument = p.sample ? `sample(${quote(p.sample)})` : `synth(${quote(p.preset || 'glass-lead')})`; return `track(${quote(id)}, ${pattern(p.notes || [])}, ${instrument}, {gain: ${number(p.gain ?? -6)}})`;
  });
  const edit = patches.reduceRight((otherwise, [id, value]) => `if t.id == ${quote(id)} { ${value} } else { ${otherwise} }`, 't');
  return `// Generated by muzstatic Studio. Original source: ${state.baseEntry.replace(/[\r\n]/g, '')}\n// Piano-roll replacements use performed notes, with explicit gate = 1.\nuse ${quote('./' + state.baseEntry)} as authored;\nlet original = if contains(keys(authored), "main") { authored.main } else { authored.__result };\nlet edited = map(${filter}, fn(t) => ${edit});\nsong(merge(original, {title: ${quote(title)}, tracks: edited${added.length ? ` + [${added.join(',\n  ')}]` : ''}${state.tempo === undefined ? '' : `, tempo: ${number(state.tempo)}`}}))\n`;
}
export function applyStudioEdit(project, id, patch) {
  const state = project.studio ? structuredClone(project.studio) : { version: 1, baseEntry: project.entry, generated: 'studio.muz', tracks: {} };
  if (!project.studio) { let i = 2; while (state.generated in project.files || state.generated in project.assets) state.generated = `studio-${i++}.muz`; }
  if (id === null) Object.assign(state, patch);
  else state.tracks = { ...state.tracks, [id]: { ...(state.tracks[id] || {}), ...patch } };
  const files = { ...project.files, [state.generated]: studioSource(state, project.title) };
  return { ...project, entry: state.generated, files, studio: normalizeStudio(state, files, project.assets) };
}
