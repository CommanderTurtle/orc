March 22&ndash;28, 2026. Park City, Utah. A ski week that turned out to be the last ski week &mdash; at least, the last one for most of the Wasatch.

## Arriving on the Wrong Day

The timing could not have been more symbolic. We landed in Park City on **Sunday, March 22** &mdash; the exact day [Snowbasin announced it was closing for the season](https://www.deseret.com/lifestyle/2026/03/19/utah-record-low-snowfall-ski-resorts-closing-warm-temperatures/), capping the year with a party on Earl's Patio. The 2025&ndash;26 season was the lowest-snowfall winter in Utah's recorded history, and by mid-March a heatwave was finishing the job. A Deseret News report from that week quoted OpenSnow's forecaster calling it "a monstrous heatwave" accelerating "an early melt-off of the snowpack," and Vail Resorts &mdash; which operates Park City Mountain &mdash; called it "the most challenging winter across the Rockies that we have ever experienced," with the lowest combined snowfall in more than thirty years.

Alta, as always, led the state at 260 inches &mdash; and that was still only about half its annual average.

## A Week of Warm Mornings

The weather for the week itself (open-meteo, Park City grid point) reads like a forecast from the wrong month: highs between **13 and 21 °C**, lows hovering just above freezing, and not a single millimeter of snowfall on any of the seven days. Drizzle on the 25th and the 28th. The first actual snow of the stretch did not arrive until the 31st, after we were gone.

Skiable anyway. Spring skiing is its own discipline &mdash; firm morning corduroy over a shrinking base, warm afternoons that end the day early. And because the season was visibly winding down, the mountain felt like it belonged to us. Crowds thinned out day by day as resorts around the valley announced their exits, and on the days the back bowls came back online after avalanche-control crews cleared them, the **Ninety-Nine-Ninety** bowls specifically, it genuinely felt like we had the whole mountain to ourselves.

## The Last Lifts

The formal ending came while we were still there. On **March 27**, Park City Mountain announced it would [wind down Mountain Village that weekend](https://townlift.com/2026/03/park-city-mountain-pulls-the-plug-on-mountain-village-this-weekend/): the Payday and Crescent lifts ran for the last time on Saturday the 28th &mdash; our final day &mdash; and the First Time and 3 Kings spins stopped on Sunday the 29th, nearly three weeks ahead of the originally scheduled April 19 close. Deer Valley announced its own season-end for the same day, which the local paper noted was a rare moment of both major Park City destinations calling it a winter simultaneously. Canyons Village kept running as long as conditions allowed; everything else shut by April 5.

The season that was supposed to run 149 days ended up at roughly 114. The opening had been delayed from November 21 to December 5 because the mountain didn't have enough snow to open safely; the closing beat its own date by three weeks. Bookended by weather, both ends.

## Why Go

Because the alternative was watching the powder reports from the couch, and the Ninety-Nines do not wait for ideal conditions. You go when the bowls reopen, you go when the lifts are winding down, you go when the thermometer says April. The receipts don't care about the snowpack statistics; they only remember the quiet days.
